/** Display labels only; protocol values and stored evidence remain unchanged. */
export function chinese(value: unknown): string {
  if (value === null || value === undefined || value === "") return "未上报";
  if (typeof value === "boolean") return value ? "是" : "否";
  const text = String(value);
  return labels[text] ?? text;
}

export function displayName(value: unknown): string {
  return String(value ?? "未命名")
    .replace(
      /^(ADMIN|ENGINEER|OPERATOR) \/ DEMO$/,
      (_, role: string) => labels[role] ?? role,
    )
    .replace(/^\s*Frame /, "画面 ")
    .replace(/^\s*file-/, "手机样本 ")
    .replace("UI verification", "界面验证账号")
    .replace("SIMULATED · Lab Device ", "模拟设备 ")
    .replace(/SIMULATED · Demo sample\s*/i, "模拟样本 ")
    .replace("SIMULATED defect model", "模拟缺陷检测模型")
    .replace("SIMULATED defect review", "模拟缺陷验收方案")
    .replace("DEMO · Surface defects", "表面缺陷演示数据集")
    .replace("SIMULATED · initial fixture deployment", "模拟模型初始部署")
    .replace(/SIMULATED Frame /g, "模拟画面 ")
    .replace(/^Frame /, "画面 ")
    .replace(/^DEMO\s*[·/]\s*/, "")
    .replace(/^SIMULATED\s*[·/]?\s*/, "模拟 · ");
}

