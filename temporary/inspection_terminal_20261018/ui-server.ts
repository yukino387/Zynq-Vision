import "reflect-metadata";
import { readdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
async function main() {
const task = resolve("temporary/inspection_terminal_20261018");
const run = readdirSync(task).filter(name=>name.startsWith("run-")).sort().at(-1)!;
process.env.DATABASE_URL=`file:${resolve(task,run,"test.db").replaceAll("\\","/")}`;
process.env.STORAGE_ROOT=resolve(task,run,"storage");
process.env.JWT_SECRET="isolated-inspection-test-at-least-thirty-two-characters";
process.env.SERVER_PORT="38881";
const {createApp}=await import("../../apps/server/src/bootstrap.js");
const {Db}=await import("../../apps/server/src/core/db.js");
const {DevicesService}=await import("../../apps/server/src/devices/devices.service.js");
const {Events}=await import("../../apps/server/src/core/events.js");
const sharp=(await import("../../apps/server/node_modules/sharp/lib/index.js")).default;
const app=await createApp(false),db=app.get(Db),devices=app.get(DevicesService),events=app.get(Events);
const device=await db.device.findFirstOrThrow({where:{type:"ZYNQ"}});
const model=await db.model.findFirstOrThrow({where:{source:"IMPORT"}});
const terminalBatch=await db.inspectionBatch.findFirstOrThrow({where:{deviceId:device.id}});
const snapshot=terminalBatch.snapshot as {modelPayloadSha256:string};
const state={modelVersion:model.version,modelPayloadSha256:snapshot.modelPayloadSha256,inspectionEnabled:true};
const transport=devices.transport(device.id);
const raw=Buffer.alloc(416*416*2);for(let i=0;i<416*416;i++)raw.writeUInt16LE((i%17<8)?0x8c71:0x6b4d,i*2);
const {decodeRgb565}=await import("../../packages/device-protocol/src/index.js");
const jpeg=await sharp(decodeRgb565(raw),{raw:{width:416,height:416,channels:3}}).jpeg().toBuffer();
let sequence=1000;
const boxes=[{classId:0,label:"牛奶",confidence:.95,x1:100,y1:100,x2:200,y2:250}];
transport.getCurrentConfig=()=>state;
transport.getStatus=()=>({runtimeState:"RUNNING",lastSeen:Date.now(),error:null,reportedState:state,telemetry:null});
transport.captureOnce=async()=>({frameId:++sequence,receivedAt:new Date().toISOString(),raw,preview:jpeg,width:416,height:416,format:"RGB565_LE",detections:boxes,modelState:state,telemetry:null});
const timer=setInterval(()=>events.emit("device.preview.frame",device.id,{frameId:++sequence,receivedAt:new Date().toISOString(),width:416,height:416,jpeg:jpeg.toString("base64"),detections:boxes},"BOARD"),500);
await app.listen(38881,"127.0.0.1");
writeFileSync(resolve(task,"ui-server.json"),JSON.stringify({port:38881,fixture:true}));
console.log("Isolated UI fixture ready at http://127.0.0.1:38881");
process.on("SIGTERM",()=>{clearInterval(timer);void app.close().then(()=>process.exit(0));});
}
void main().catch(error => { console.error(error); process.exit(1); });
