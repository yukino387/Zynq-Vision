import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const require=createRequire(new URL('../../apps/server/package.json',import.meta.url));
require('dotenv').config({path:new URL('../../.env',import.meta.url),quiet:true});
const {PrismaClient}=require('@prisma/client');
const db=new PrismaClient();
const base='http://127.0.0.1:3000/api';
const login=await fetch(`${base}/auth/login`,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({username:'admin',password:process.env.SEED_PASSWORD})});
const session=await login.json();
if(!login.ok)throw new Error('Local login failed');
const headers={authorization:`Bearer ${session.token}`,'content-type':'application/json'};
const original=JSON.parse(readFileSync(new URL('./baseline.json',import.meta.url),'utf8')).device;
async function request(path,body){const response=await fetch(`${base}${path}`,{method:body?'POST':'GET',headers,...(body?{body:JSON.stringify(body)}:{})});const result=await response.json();if(!response.ok)throw new Error(JSON.stringify({status:response.status,...result}));return result;}
const pendingCommands=await db.command.count({where:{status:{in:['QUEUED','RUNNING']}}});
const pendingJobs=await db.job.count({where:{status:{in:['QUEUED','RUNNING']}}});
console.log('pending',JSON.stringify({commands:pendingCommands,jobs:pendingJobs}));
assert.equal(pendingCommands+pendingJobs,0,'Do not restart or evaluate while other operations are active');
if(process.argv.includes('--connect'))await request(`/devices/${original.id}/connect`,{});
const before=(await request('/devices/snapshot')).find(d=>d.id===original.id);
assert.equal(before.reportedState.modelVersion,original.reportedState.modelVersion);
assert.equal(before.reportedState.modelPayloadSha256,original.reportedState.modelPayloadSha256);
let result=null;
if(process.argv.includes('--evaluate')){
 const models=await request('/models?pageSize=100');
 const model=models.items.find(m=>m.version==='MILK-RGB-20261017');
 const datasets=await request('/datasets?status=FROZEN&pageSize=100');
 const start=performance.now();
 result=await request('/benchmarks',{name:'RGB 模型评估验证 20261018',modelId:model.id,datasetId:datasets.items[0].id,deviceId:original.id});
 console.log('evaluation',JSON.stringify({id:result.id,source:result.source,seconds:(performance.now()-start)/1000,metrics:result.metrics}));
 assert.equal(result.source,'BOARD');
 assert.equal(result.metrics.candidateExecuted,true);
 assert.equal(result.metrics.restoredModelPayloadSha256,original.reportedState.modelPayloadSha256);
 assert.ok(result.metrics.fps>0);
}
const after=(await request('/devices/snapshot')).find(d=>d.id===original.id);
assert.equal(after.reportedState.modelVersion,original.reportedState.modelVersion);
assert.equal(after.reportedState.modelPayloadSha256,original.reportedState.modelPayloadSha256);
assert.equal(after.runtimeState,original.runtimeState);
assert.equal(after.reportedState.cameraOnly,original.reportedState.cameraOnly);
if (!result) result=await db.benchmark.findFirst({where:{name:'RGB 模型评估验证 20261018'},orderBy:{createdAt:'desc'}});
writeFileSync(new URL('./live-verification.json',import.meta.url),JSON.stringify({result,after:{version:after.reportedState.modelVersion,payloadSha256:after.reportedState.modelPayloadSha256,runtimeState:after.runtimeState,cameraOnly:after.reportedState.cameraOnly}},null,2));
console.log('exact original model and run mode confirmed');
await db.$disconnect();
